'use client'

import { useEffect, useState } from 'react'
import { motion } from 'framer-motion'
import {
  AlertTriangle,
  ArrowLeft,
  CheckCircle2,
  Flag,
  Clock,
  BarChart2,
  Shield,
  TrendingUp,
  TrendingDown,
  Loader2,
} from 'lucide-react'
import { getAssessmentById } from '@/lib/api/assessments'
import type { Assessment, LimeFactor } from '@/lib/types/assessment'

// ─── Risk gauge ────────────────────────────────────────────────────────────────

function riskMeta(score: number) {
  if (score < 33) return { label: 'Low Risk', color: 'text-primary', ring: 'stroke-primary', bg: 'bg-primary/10' }
  if (score < 66) return { label: 'Moderate Risk', color: 'text-chart-4', ring: 'stroke-chart-4', bg: 'bg-chart-4/10' }
  return { label: 'High Risk', color: 'text-destructive', ring: 'stroke-destructive', bg: 'bg-destructive/10' }
}

function RiskGauge({ score }: { score: number }) {
  const r = 52
  const circ = 2 * Math.PI * r
  const dash = (score / 100) * circ
  const meta = riskMeta(score)

  return (
    <div className="flex flex-col items-center gap-3">
      <div className="relative size-36">
        <svg className="-rotate-90" viewBox="0 0 120 120" width="144" height="144">
          <circle cx="60" cy="60" r={r} fill="none" stroke="var(--secondary)" strokeWidth="10" />
          <motion.circle
            cx="60"
            cy="60"
            r={r}
            fill="none"
            strokeWidth="10"
            strokeLinecap="round"
            strokeDasharray={`${circ}`}
            initial={{ strokeDashoffset: circ }}
            animate={{ strokeDashoffset: circ - dash }}
            transition={{ duration: 1.2, ease: 'easeOut' }}
            className={meta.ring}
          />
        </svg>
        <div className="absolute inset-0 flex flex-col items-center justify-center">
          <span className={`font-serif text-4xl font-bold ${meta.color}`}>{score}</span>
          <span className="text-xs text-muted-foreground">/ 100</span>
        </div>
      </div>
      <span className={`rounded-full px-3 py-1 text-sm font-semibold ${meta.bg} ${meta.color}`}>
        {meta.label}
      </span>
    </div>
  )
}

// ─── LIME explainability panel ─────────────────────────────────────────────────

function LimePanel({ factors }: { factors: LimeFactor[] }) {
  const sorted = [...factors].sort((a, b) => b.weight - a.weight)
  const max = sorted[0]?.weight ?? 1

  return (
    <section className="rounded-2xl border border-border bg-card p-6">
      <div className="flex items-center gap-2">
        <BarChart2 className="size-5 text-primary" />
        <h2 className="font-serif text-lg font-semibold">Top Contributing Factors</h2>
      </div>
      <p className="mt-1 text-xs text-muted-foreground">
        Generated by the LIME explainability layer. // PLACEHOLDER — from backend
      </p>
      <div className="mt-5 space-y-3">
        {sorted.map((f) => (
          <div key={f.feature}>
            <div className="flex items-center justify-between">
              <div className="flex items-center gap-2">
                {f.direction === 'risk' ? (
                  <TrendingUp className="size-4 shrink-0 text-destructive" />
                ) : (
                  <TrendingDown className="size-4 shrink-0 text-primary" />
                )}
                <span className="text-sm font-medium">{f.feature}</span>
              </div>
              <span className={`text-xs font-semibold ${f.direction === 'risk' ? 'text-destructive' : 'text-primary'}`}>
                {f.direction === 'risk' ? '↑ risk' : '↓ protective'} {(f.weight * 100).toFixed(0)}%
              </span>
            </div>
            <div className="mt-1.5 h-2 w-full overflow-hidden rounded-full bg-secondary">
              <motion.div
                initial={{ width: 0 }}
                animate={{ width: `${(f.weight / max) * 100}%` }}
                transition={{ duration: 0.8, ease: 'easeOut', delay: 0.1 }}
                className={`h-full rounded-full ${f.direction === 'risk' ? 'bg-destructive/70' : 'bg-primary/70'}`}
              />
            </div>
          </div>
        ))}
      </div>
    </section>
  )
}

// ─── Review status badge ───────────────────────────────────────────────────────

function ReviewBadge({ status }: { status: Assessment['status'] }) {
  const map = {
    draft: { label: 'Draft', icon: Clock, cls: 'bg-secondary text-muted-foreground' },
    submitted: { label: 'Processing', icon: Loader2, cls: 'bg-chart-2/10 text-chart-2' },
    pending_review: { label: 'Pending Clinician Review', icon: Clock, cls: 'bg-chart-4/10 text-chart-4' },
    confirmed: { label: 'Clinician Confirmed', icon: CheckCircle2, cls: 'bg-primary/10 text-primary' },
    flagged: { label: 'Flagged for Second Opinion', icon: Flag, cls: 'bg-destructive/10 text-destructive' },
  }
  const m = map[status]
  const Icon = m.icon
  return (
    <span className={`inline-flex items-center gap-1.5 rounded-full px-3 py-1 text-xs font-semibold ${m.cls}`}>
      <Icon className="size-3.5" />
      {m.label}
    </span>
  )
}

// ─── Main component ────────────────────────────────────────────────────────────

interface Props {
  assessmentId: string
  onBack: () => void
}

export function AssessmentResults({ assessmentId, onBack }: Props) {
  const [assessment, setAssessment] = useState<Assessment | null>(null)
  const [loading, setLoading] = useState(true)
  const [error, setError] = useState<string | null>(null)

  useEffect(() => {
    let cancelled = false
    setLoading(true)
    getAssessmentById(assessmentId)
      .then((a) => { if (!cancelled) { setAssessment(a); setLoading(false) } })
      .catch(() => { if (!cancelled) { setError('Failed to load assessment.'); setLoading(false) } })
    return () => { cancelled = true }
  }, [assessmentId])

  if (loading) {
    return (
      <div className="flex min-h-64 flex-col items-center justify-center gap-3">
        <Loader2 className="size-8 animate-spin text-primary" />
        <p className="text-sm text-muted-foreground">Loading your results…</p>
      </div>
    )
  }

  if (error || !assessment) {
    return (
      <div className="flex min-h-64 flex-col items-center justify-center gap-3 rounded-2xl border border-destructive/30 bg-destructive/10 p-8">
        <AlertTriangle className="size-8 text-destructive" />
        <p className="text-sm text-destructive">{error ?? 'Assessment not found.'}</p>
        <button type="button" onClick={onBack} className="rounded-xl border border-border px-4 py-2 text-sm">
          Go back
        </button>
      </div>
    )
  }

  const rs = assessment.riskScore

  return (
    <motion.div
      initial={{ opacity: 0, y: 12 }}
      animate={{ opacity: 1, y: 0 }}
      transition={{ duration: 0.35 }}
      className="space-y-6"
    >
      {/* Header */}
      <div className="flex items-start gap-3">
        <button
          type="button"
          onClick={onBack}
          className="mt-1 flex size-9 shrink-0 items-center justify-center rounded-xl border border-border transition-colors hover:bg-secondary"
        >
          <ArrowLeft className="size-4" />
        </button>
        <div>
          <h1 className="font-serif text-2xl font-bold tracking-tight md:text-3xl">Assessment Results</h1>
          <p className="mt-0.5 text-sm text-muted-foreground">
            {new Date(assessment.createdAt).toLocaleDateString('en-IN', {
              day: 'numeric', month: 'long', year: 'numeric',
            })}
          </p>
        </div>
      </div>

      {/* Review status */}
      <div className="flex flex-wrap gap-2">
        <ReviewBadge status={assessment.status} />
        <span className="inline-flex items-center gap-1.5 rounded-full bg-secondary px-3 py-1 text-xs font-medium text-muted-foreground">
          {assessment.source === 'clinic_admin' ? '🏥 Clinic-administered' : '📱 Self-service'}
        </span>
      </div>

      {rs ? (
        rs.fallback ? (
          /* ── Fallback: KL-grade only ─────────────────────────────────────────── */
          <div className="space-y-5">
            <motion.div
              initial={{ opacity: 0 }}
              animate={{ opacity: 1 }}
              className="flex flex-col gap-4 rounded-2xl border border-chart-4/40 bg-chart-4/8 p-6 sm:flex-row sm:items-center"
            >
              <AlertTriangle className="size-8 shrink-0 text-chart-4" />
              <div>
                <h2 className="font-serif text-lg font-bold text-chart-4">
                  Low-confidence fusion — KL grade shown only
                </h2>
                <p className="mt-1 text-sm text-muted-foreground">
                  Fusion confidence was <strong>{(rs.confidence * 100).toFixed(0)}%</strong> —
                  below the threshold required to display a combined score.{' '}
                  {/* PLACEHOLDER — threshold set by backend */}
                  KL grade is derived from your X-ray or clinical examination.
                </p>
              </div>
            </motion.div>

            {rs.klGrade !== null && (
              <div className="flex items-center gap-6 rounded-2xl border border-border bg-card p-6">
                <div className="flex size-20 shrink-0 items-center justify-center rounded-2xl bg-chart-4/10">
                  <span className="font-serif text-4xl font-bold text-chart-4">
                    {rs.klGrade}
                  </span>
                </div>
                <div>
                  <p className="text-xs font-semibold uppercase tracking-wide text-muted-foreground">
                    Kellgren–Lawrence Grade
                  </p>
                  <p className="mt-1 font-serif text-xl font-bold">
                    {['None', 'Doubtful', 'Minimal', 'Moderate', 'Severe'][rs.klGrade]}
                  </p>
                  <p className="mt-1 text-xs text-muted-foreground">
                    {/* PLACEHOLDER — clinical text from backend */}
                    Grade definitions are from the Kellgren–Lawrence radiographic grading system.
                  </p>
                </div>
              </div>
            )}

            {rs.limeFactors.length > 0 && <LimePanel factors={rs.limeFactors} />}
          </div>
        ) : (
          /* ── Full fused result ───────────────────────────────────────────────── */
          <div className="space-y-5">
            {/* Combined score card */}
            <div className="rounded-2xl border border-border bg-card p-6 sm:p-8">
              <div className="flex flex-col items-center gap-6 sm:flex-row sm:items-start">
                <RiskGauge score={rs.combined} />
                <div className="flex-1 space-y-4">
                  <div>
                    <p className="text-xs font-semibold uppercase tracking-wide text-muted-foreground">
                      Combined OA Risk Score {/* PLACEHOLDER */}
                    </p>
                    <p className="mt-1 text-sm leading-relaxed text-muted-foreground">
                      Fused from your gait video and clinical questionnaire responses.
                      Confidence: <strong>{(rs.confidence * 100).toFixed(0)}%</strong>.{' '}
                      {/* PLACEHOLDER — from backend fusion */}
                    </p>
                  </div>

                  {/* Sub-scores */}
                  <div className="grid grid-cols-2 gap-3">
                    <SubScore label="Gait sub-score" value={rs.gait} icon={TrendingUp} />
                    <SubScore label="Clinical sub-score" value={rs.clinical} icon={BarChart2} />
                  </div>

                  {/* KL grade */}
                  {rs.klGrade !== null && (
                    <div className="flex items-center gap-3 rounded-xl border border-border bg-secondary/50 px-4 py-2.5">
                      <Shield className="size-4 text-primary" />
                      <span className="text-sm">
                        KL Grade: <strong>{rs.klGrade}</strong> —{' '}
                        {['None', 'Doubtful', 'Minimal', 'Moderate', 'Severe'][rs.klGrade]}
                      </span>
                    </div>
                  )}
                </div>
              </div>
            </div>

            <LimePanel factors={rs.limeFactors} />

            {/* Clinician note */}
            {assessment.reviewNote && (
              <section className="rounded-2xl border border-border bg-card p-5">
                <p className="text-xs font-semibold uppercase tracking-wide text-muted-foreground">
                  Clinician Note
                </p>
                <p className="mt-2 text-sm leading-relaxed">{assessment.reviewNote}</p>
                <p className="mt-2 text-xs text-muted-foreground">
                  Reviewed by {assessment.reviewedBy} ·{' '}
                  {assessment.reviewedAt
                    ? new Date(assessment.reviewedAt).toLocaleDateString('en-IN', { day: 'numeric', month: 'long', year: 'numeric' })
                    : ''}
                </p>
              </section>
            )}
          </div>
        )
      ) : (
        <div className="flex min-h-40 items-center justify-center rounded-2xl border border-dashed border-border bg-secondary/40">
          <p className="text-sm text-muted-foreground">Results are being processed…</p>
        </div>
      )}
    </motion.div>
  )
}

function SubScore({
  label,
  value,
  icon: Icon,
}: {
  label: string
  value: number
  icon: typeof BarChart2
}) {
  const meta = riskMeta(value)
  return (
    <div className={`rounded-xl border border-border p-3 ${meta.bg}`}>
      <div className="flex items-center gap-1.5">
        <Icon className={`size-3.5 ${meta.color}`} />
        <span className="text-xs text-muted-foreground">{label}</span>
      </div>
      <p className={`mt-1 font-serif text-2xl font-bold ${meta.color}`}>{value}</p>
    </div>
  )
}
